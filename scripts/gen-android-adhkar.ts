// Writes the site's أذكار الصباح والمساء (src/lib/adhkar-data.ts) into the Android app as
// Kotlin data, so both read the same list. Re-run after editing adhkar-data.ts:
//   node_modules/.bin/tsx scripts/gen-android-adhkar.ts
// ponytail: generated source, not pipeline content — move into app/v2 if more أبواب arrive.
import { writeFileSync } from "node:fs";
import { MORNING, EVENING, type AdhkarItem } from "../src/lib/adhkar-data.js";

const out = "android/app/src/main/kotlin/com/atharchive/feature/adhkar/AdhkarData.kt";
const kt = (s: string) => JSON.stringify(s).replace(/\$/g, "\\$");

function list(items: AdhkarItem[]): string {
  if (new Set(items.map((i) => i.id)).size !== items.length) throw new Error("duplicate adhkar id");
  return items
    .map((i) => {
      if (!i.text.trim() || !(i.count >= 1)) throw new Error(`bad adhkar item ${i.id}`);
      const source = i.source ? `, source = ${kt(i.source)}` : "";
      return `        DhikrUi(id = ${kt(i.id)}, text = ${kt(i.text)}, repeat = ${i.count}${source}),`;
    })
    .join("\n");
}

writeFileSync(
  out,
  `// GENERATED by scripts/gen-android-adhkar.ts from src/lib/adhkar-data.ts — do not edit.
package com.atharchive.feature.adhkar

val AdhkarContent = AdhkarUiState(
    headline = "أذكار الصباح والمساء",
    babs = listOf(
        AdhkarBabUi("morning", "الصباح", frequent = true),
        AdhkarBabUi("evening", "المساء", frequent = true),
    ),
    entries = mapOf(
        "morning" to listOf(
${list(MORNING)}
        ),
        "evening" to listOf(
${list(EVENING)}
        ),
    ),
)
`,
);
console.log(`${out}: ${MORNING.length} morning, ${EVENING.length} evening`);
